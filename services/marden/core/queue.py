"""The Procrastinate app (Postgres-backed job queue on DATABASE_URL).

Modules declare tasks on `app` at import time:

    from marden.core.queue import app

    @app.task(name="collect.sec_edgar", queue="collect", queueing_lock="collect.sec_edgar")
    def collect_sec_edgar() -> None: ...

The schema lives in db/migrations/20261021100100_procrastinate.sql (generated by
`procrastinate schema --read`). The worker is `python -m marden worker` (marden.worker).
"""

from __future__ import annotations

import procrastinate

from marden.core.config import get_settings

QUEUES = ("default", "collect", "extract", "models", "readmodels")


def make_connector() -> procrastinate.PsycopgConnector:
    """A connector for the current DATABASE_URL (read when called, so call after setting env)."""
    url = get_settings().database_url
    return procrastinate.PsycopgConnector(conninfo=url) if url else procrastinate.PsycopgConnector()


app = procrastinate.App(connector=make_connector())
